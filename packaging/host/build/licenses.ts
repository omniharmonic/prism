/**
 * THIRD-PARTY-LICENSES.md for the host bundle: every package shipped in node_modules
 * (name, version, declared licence, and its licence file text) plus the Node.js runtime.
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

export interface ShippedPackage {
  name: string;
  version: string;
  license: string;
  homepage: string | null;
  texts: string[];
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;

function licenseTexts(dir: string): string[] {
  const out: string[] = [];
  for (const f of readdirSync(dir).sort()) {
    if (!LICENSE_FILE.test(f)) continue;
    const p = join(dir, f);
    if (statSync(p).isFile() && statSync(p).size < 256 * 1024) out.push(readFileSync(p, "utf8").trim());
  }
  return out;
}

function declared(pkg: { license?: unknown; licenses?: unknown }): string {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license && typeof pkg.license === "object" && "type" in pkg.license) return String((pkg.license as { type: unknown }).type);
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l: { type?: unknown }) => String(l?.type ?? "?")).join(" OR ");
  return "UNKNOWN";
}

/** Read every package folder under `nodeModules` (scopes and nested node_modules included). */
export function collectPackages(nodeModules: string): ShippedPackage[] {
  const seen = new Map<string, ShippedPackage>();
  const walk = (nm: string) => {
    if (!existsSync(nm)) return;
    for (const entry of readdirSync(nm).sort()) {
      if (entry.startsWith(".")) continue;
      const dirs = entry.startsWith("@") ? readdirSync(join(nm, entry)).map((s) => join(entry, s)) : [entry];
      for (const d of dirs) {
        const dir = join(nm, d);
        const pj = join(dir, "package.json");
        if (!existsSync(pj)) continue;
        try {
          if (!statSync(dir).isDirectory()) continue;
        } catch {
          continue; // a dangling link
        }
        const pkg = JSON.parse(readFileSync(pj, "utf8")) as { name?: string; version?: string; license?: unknown; licenses?: unknown; homepage?: unknown; private?: boolean };
        if (pkg.name && pkg.version && !pkg.private) {
          const key = `${pkg.name}@${pkg.version}`;
          if (!seen.has(key)) seen.set(key, { name: pkg.name, version: pkg.version, license: declared(pkg), homepage: typeof pkg.homepage === "string" ? pkg.homepage : null, texts: licenseTexts(dir) });
        }
        walk(join(dir, "node_modules"));
      }
    }
  };
  walk(nodeModules);
  return [...seen.values()].sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));
}

export function renderLicenses(pkgs: ShippedPackage[], node: { version: string; licenseText: string }, title: string): string {
  const lines: string[] = [
    `# Third-party software in ${title}`,
    "",
    "Generated by packaging/host/build.ts from the files that ship in this bundle. Prism itself is",
    "licensed under PolyForm Shield 1.0.0 (LICENSE.md). The components below keep their own licences.",
    "",
    "| Component | Version | Licence |",
    "|---|---|---|",
    `| Node.js | ${node.version} | MIT and others (see below) |`,
    ...pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    "",
    "---",
    "",
    `## Node.js ${node.version}`,
    "",
    "```",
    node.licenseText.trim(),
    "```",
    "",
  ];
  for (const p of pkgs) {
    lines.push(`## ${p.name} ${p.version} — ${p.license}`, "");
    if (p.homepage) lines.push(p.homepage, "");
    if (p.texts.length === 0) lines.push("_No licence file in the package; its package.json declares the licence above._", "");
    for (const t of p.texts) lines.push("```", t, "```", "");
  }
  return lines.join("\n");
}
